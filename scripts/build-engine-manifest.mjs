#!/usr/bin/env node
/**
 * Generate `engine-manifest.json` from a local checkout of the pinned engine.
 *
 * Run by hand, only when `EXTERNAL_ENGINE.lock` moves:
 *
 *   node scripts/build-engine-manifest.mjs /path/to/bridgistic-claude-marketplace
 *
 * The manifest is committed so `check-tool-drift.mjs` runs offline. A drift
 * check that clones a repository is a check that fails when GitHub is slow,
 * and a check that fails for reasons unrelated to the code is one people learn
 * to re-run without reading.
 *
 * It refuses to run against a checkout at the wrong commit, because a manifest
 * built from "whatever was checked out" is a record of nothing.
 */

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join } from "node:path";

const checkout = process.argv[2];
if (!checkout) {
  console.error("usage: node scripts/build-engine-manifest.mjs <path-to-engine-checkout>");
  process.exit(2);
}

const lock = readFileSync("EXTERNAL_ENGINE.lock", "utf8");
const pinned = lock.match(/^commit\s*=\s*(\S+)$/m)?.[1];
if (!pinned) {
  console.error("EXTERNAL_ENGINE.lock has no commit.");
  process.exit(2);
}

const head = execFileSync("git", ["-C", checkout, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
if (head !== pinned) {
  console.error(
    `Checkout is at ${head}, EXTERNAL_ENGINE.lock pins ${pinned}.\n` +
      `Check out the pinned commit, or update the lock in the same change that updates the manifest.`
  );
  process.exit(1);
}

const remote = execFileSync("git", ["-C", checkout, "remote", "get-url", "origin"], { encoding: "utf8" }).trim();
if (!/bridgistic-claude-marketplace(\.git)?$/i.test(remote)) {
  console.error(`Checkout's origin is ${remote}, which is not the engine repository.`);
  process.exit(1);
}

const toolsDir = join(checkout, "cloud/src/tools");
const tools = [];

for (const file of readdirSync(toolsDir).filter((f) => f.endsWith(".ts"))) {
  const source = readFileSync(join(toolsDir, file), "utf8");
  for (const match of source.matchAll(/registerTool\(\s*"([a-z_]+)"/g)) {
    const name = match[1];

    // Bounded by the NEXT registerTool call, not by a fixed character count.
    // A fixed window spills into the following tool's description, and the
    // scope prose it picks up there is attributed to this tool — which is
    // exactly the false drift the check reported the first time it ran.
    const after = source.slice(match.index + match[0].length);
    const nextCall = after.search(/registerTool\(\s*"/);
    const tail = nextCall === -1 ? after : after.slice(0, nextCall);

    // The scope each tool documents, e.g. "Scope: `posts:read`."
    const scopes = [...tail.matchAll(/Scope:\s*`([a-z:]+)`/g)].map((m) => m[1]);

    tools.push({
      name,
      file,
      scopes: [...new Set(scopes)].sort(),
      args: argNames(tail),
    });
  }
}

tools.sort((a, b) => a.name.localeCompare(b.name));

const manifest = {
  $comment:
    "Generated by scripts/build-engine-manifest.mjs from the commit pinned in EXTERNAL_ENGINE.lock. " +
    "Do not edit by hand. Regenerate when the pin moves.",
  commit: pinned,
  generatedFrom: remote,
  toolCount: tools.length,
  tools,
};

writeFileSync("engine-manifest.json", `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`Wrote engine-manifest.json — ${tools.length} tools at ${pinned.slice(0, 12)}.`);

/** Top-level argument names from a Zod `inputSchema: { ... }` block. */
function argNames(tail) {
  const start = tail.search(/inputSchema:\s*\{/);
  if (start === -1) return [];
  const open = tail.indexOf("{", start);
  let depth = 0;
  let end = open;
  for (let i = open; i < tail.length; i++) {
    if (tail[i] === "{") depth++;
    else if (tail[i] === "}") {
      depth--;
      if (depth === 0) {
        end = i;
        break;
      }
    }
  }
  const body = tail.slice(open + 1, end);

  const names = [];
  let nesting = 0;
  for (const line of body.split(/,(?![^(]*\))/)) {
    // Only names at depth 0 of this object are arguments; anything inside a
    // nested z.object() belongs to that shape.
    // `name: schema` and the shorthand `name,` — the engine uses both, and
    // missing the shorthand reported `recurrence` as a hosted-only invention.
    const key = line.match(/^\s*([a-z_][a-z0-9_]*)\s*(?::|$)/i);
    if (nesting === 0 && key) names.push(key[1]);
    if (nesting === 0 && /\.\.\.guardParams/.test(line)) names.push("dry_run", "approval_id", "force");
    nesting += (line.match(/\{/g) ?? []).length - (line.match(/\}/g) ?? []).length;
  }
  return [...new Set(names)].sort();
}
