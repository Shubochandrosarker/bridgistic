#!/usr/bin/env node
/**
 * Every tool's route and method must exist on the WordPress plugin.
 *
 * BR-019. The tool catalogue carried a route and an HTTP method for all 54
 * tools, and nothing in the repository compared either against the plugin.
 * `check-tool-drift.mjs` compares tool NAMES and ARGUMENTS to the engine
 * manifest, which is a different question — so a catalogue whose routes had
 * drifted from the plugin passed typecheck, 350-odd tests and every hygiene
 * check, while a fifth of the tools would have returned 404 or 405 against a
 * real site. The first place that would have surfaced is a customer's install.
 *
 * Runs offline against `plugin-routes.json`, regenerated by
 * `scripts/build-plugin-routes.mjs` when `EXTERNAL_ENGINE.lock` moves.
 */

import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";

const fixture = JSON.parse(readFileSync("plugin-routes.json", "utf8"));
const pinned = readFileSync("EXTERNAL_ENGINE.lock", "utf8").match(/^commit\s*=\s*(\S+)$/m)?.[1];

if (fixture.engineCommit !== pinned) {
  console.error(
    `plugin-routes.json was built from ${fixture.engineCommit?.slice(0, 12)}, ` +
      `EXTERNAL_ENGINE.lock pins ${pinned?.slice(0, 12)}.\n` +
      `Regenerate it: node scripts/build-plugin-routes.mjs <engine-checkout>`
  );
  process.exit(1);
}

const plugin = new Set(fixture.routes);

// Read the catalogue through Node's type stripping, the same way the tests do,
// so this checks the values the platform actually uses rather than a parse of
// the source.
const catalogue = JSON.parse(
  execFileSync(
    process.execPath,
    [
      "-e",
      `Promise.all([import("./packages/tools/src/index.ts"), import("./packages/contracts/src/index.ts")]).then(
         ([tools, contracts]) => {
           console.log(
             JSON.stringify(
               tools.TOOLS.map((t) => ({
                 name: t.name,
                 route: t.route,
                 method: t.method,
                 required: contracts.contractFor(t.name)?.inputSchema?.required ?? [],
               }))
             )
           );
         }
       );`,
    ],
    { encoding: "utf8" }
  ).trim()
);

const problems = [];
for (const tool of catalogue) {
  if (tool.route === null || tool.method === null) continue;
  const wanted = `${tool.method} ${tool.route}`;
  if (plugin.has(wanted)) continue;

  // A route the plugin serves under a different method is the more dangerous
  // shape: it looks present, and fails at the call.
  const sameRoute = [...plugin].filter((r) => r.slice(r.indexOf(" ") + 1) === tool.route);
  const hint =
    sameRoute.length > 0
      ? `the plugin serves that route as ${sameRoute.join(", ")}`
      : `the plugin has no route "${tool.route}"`;
  problems.push(`${tool.name}: declares "${wanted}" — ${hint}`);
}

// A tool that requires an identifier and whose route carries no placeholder is
// pointing at a collection where it means one item. The route comparison above
// cannot see this — the collection route exists, so nothing 404s. It is the
// worse failure: `bridgistic_update_post` declaring `POST posts` reaches the
// plugin's CREATE handler and silently makes a new post instead of editing the
// one asked for, and `bridgistic_update_user` creates a WordPress user.
const IDENTIFIER_PARAMS = new Set(["id", "slug"]);
for (const tool of catalogue) {
  if (tool.route === null) continue;
  const identifier = (tool.required ?? []).find((p) => IDENTIFIER_PARAMS.has(p));
  if (identifier === undefined) continue;
  if (tool.route.includes(`{${identifier}}`)) continue;

  // Only when the plugin serves an item route under the SAME method. An
  // identifier in the body is normal — `POST playbooks/delete` takes a slug
  // that way, and there is no `POST playbooks/delete/{slug}` to confuse it
  // with. The problem is only where both forms exist under one method and the
  // collection one does something else: `POST posts` creates, `POST posts/{id}`
  // updates.
  const itemRoute = `${tool.method} ${tool.route}/{${identifier}}`;
  if (!plugin.has(itemRoute)) continue;

  problems.push(
    `${tool.name}: requires "${identifier}" but its route is the collection "${tool.method} ${tool.route}" — ` +
      `the plugin serves "${itemRoute}", and the collection route under this method does something else`
  );
}

if (problems.length > 0) {
  console.error(`Tool routes that no site will answer (${problems.length}):\n  ${problems.join("\n  ")}`);
  console.error(
    `\nThe plugin's routes are in plugin-routes.json, generated from the pinned engine.\n` +
      `Fix the catalogue — the plugin is the authority on what a site answers.`
  );
  process.exit(1);
}

console.log(`check-plugin-routes: ${catalogue.filter((t) => t.route).length} site-calling tools, every route served.`);
